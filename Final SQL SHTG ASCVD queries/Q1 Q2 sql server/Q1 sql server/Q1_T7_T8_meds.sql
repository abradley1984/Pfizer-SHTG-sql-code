    IIF(nhdl >= 130, 1, 0) as nhdl_above_130,
    IIF(TG_result_num >= 150, 1, 0) as TG_above_150,
    IIF(datediff(dd, first_therapy_date, last_therapy_date_in_sp) < 90, 1, 0) as less_than_3_months_therapy
    FROM #all_meds) n;

